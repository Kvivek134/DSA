#Demonstrate assignment operators (+=, -=, *=, /=).
x = 10
x += 5  # Equivalent to x = x + 5
print("After += 5, x =", x)
x -= 3  # Equivalent to x = x - 3
print("After -= 3, x =", x)
x *= 2  # Equivalent to x = x * 2
print("After *= 2, x =", x)
x /= 4  # Equivalent to x = x / 4
print("After /= 4, x =", x)
